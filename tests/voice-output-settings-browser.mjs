import { chromium, expect } from "@playwright/test";
import { mkdir } from "node:fs/promises";
import { createSettingsHost } from "./settings-host.mjs";
import { denyNativeNotifications } from "./notification-permission.mjs";

const server = await createSettingsHost();
const browser = await chromium.launch({ channel: "chrome", headless: true });
const evidence = ".scratch/elevenlabs-output-key";
await mkdir(evidence, { recursive: true });
try {
  for (const width of [390, 1280]) {
    const context = await browser.newContext({ viewport: { width, height: 844 }, locale: "zh-CN" });
    await context.addInitScript(denyNativeNotifications);
    const page = await context.newPage();
    page.setDefaultTimeout(12000);
    const errors = [];
    page.on("pageerror", (error) => errors.push(String(error)));
    const state = { provider: "alibaba", voices: { minimax: "minimax-id", alibaba: "Cherry", bytedance: "byte-id", elevenlabs: "old-id" }, speeds: { minimax: 1.2, bytedance: null }, configured: { alibaba: true, bytedance: false, elevenlabs: false } };
    let ambiguous = false;
    let ambiguousSelection = false;
    let selectionPosts = 0;
    let voiceAccessDenied = false;
    let voicesEmpty = false;
    let keyPosts = 0;
    let voicePages = [];
    await page.route("**/api/tts/settings", async (route) => {
      if (route.request().method() === "POST") {
        selectionPosts++;
        if (ambiguousSelection) return route.abort("failed");
        const body = route.request().postDataJSON();
        state.provider = body.provider;
        state.voices[body.provider] = body.voice;
        if (body.provider === "minimax" || body.provider === "bytedance") state.speeds[body.provider] = body.speed;
      }
      return route.fulfill({ json: state });
    });
    await page.route("**/api/tts/settings/key", async (route) => {
      keyPosts++;
      const body = route.request().postDataJSON();
      expect(body).toEqual({ provider: "elevenlabs", apiKey: ambiguous ? "synthetic-replacement" : "synthetic-key" });
      if (ambiguous) return route.abort("failed");
      state.configured.elevenlabs = true;
      return route.fulfill({ json: state });
    });
    await page.route("**/api/tts/elevenlabs/voices**", (route) => {
      if (voiceAccessDenied) return route.fulfill({ status: 403 });
      if (voicesEmpty) return route.fulfill({ json: { voices: [], nextCursor: null } });
      const cursor = new URL(route.request().url()).searchParams.get("cursor");
      voicePages.push(cursor);
      return route.fulfill({ json: cursor ? { voices: [{ id: "v2", name: "音色二" }], nextCursor: null } : { voices: [{ id: "v1", name: "音色一" }], nextCursor: "next" } });
    });
    await page.goto(`http://127.0.0.1:${server.port}/`);
    const draft = page.locator("#companion-textarea");
    await draft.fill("保留草稿");
    await page.getByRole("button", { name: "设置", exact: true }).click();
    const settings = page.locator(".settings-screen");
    await expect(settings.getByRole("button", { name: "语音输出", exact: true })).toBeVisible();
    await expect(settings.getByRole("button", { name: "语音输入", exact: true })).toHaveCount(0);
    await page.screenshot({ path: `${evidence}/${width}-settings-home.png`, animations: "disabled" });
    await settings.getByRole("button", { name: "语音输出", exact: true }).click();
    const provider = settings.locator("#tts-provider");
    async function chooseSmart(id, value) {
      const trigger = settings.locator(`#${id}`);
      if (id === "tts-provider" && value === "minimax") {
        await trigger.focus();
        await expect(trigger).toBeFocused();
        await trigger.press("Enter");
      } else await trigger.click();
      const picker = page.getByTestId("voice-settings-picker");
      await expect(picker).toBeVisible();
      if ((id === "tts-provider" && value === "minimax") || (id === "tts-saved-voices" && value === "saved:v2"))
        await page.screenshot({ path: `${evidence}/${width}-${id}-open.png`, animations: "disabled" });
      await picker.locator(`[data-value="${value}"]`).click();
      await expect(picker).toHaveCount(0);
    }
    async function expectVoiceChoices(count) {
      await settings.locator("#tts-saved-voices").click();
      const picker = page.getByTestId("voice-settings-picker");
      await expect(picker.locator("[data-value]")).toHaveCount(count);
      await picker.getByRole("button", { name: "取消" }).click();
      await expect(settings.locator("#tts-saved-voices")).toBeFocused();
    }
    await expect(provider).toHaveAttribute("data-value", "alibaba");
    await expect(provider).toBeVisible();
    await expect(settings.locator("#tts-voice")).toHaveValue("Cherry");
    await chooseSmart("tts-provider", "minimax");
    await expect(settings.locator("#tts-key")).toHaveCount(0);
    await expect(settings.locator("#tts-speed")).toHaveValue("1.2");
    await settings.locator("#tts-speed").fill("1.4");
    await page.goBack();
    await page.goBack();
    await page.goForward();
    await page.goForward();
    await expect(provider).toHaveAttribute("data-value", "minimax");
    await expect(settings.locator("#tts-speed")).toHaveValue("1.4");
    await chooseSmart("tts-provider", "bytedance");
    await expect(settings.locator("#tts-voice")).toHaveValue("byte-id");
    await chooseSmart("tts-provider", "elevenlabs");
    const input = settings.locator("#tts-key");
    await expect(input).toHaveAttribute("type", "password");
    await expect(settings.getByLabel("API Key")).toHaveCount(1);
    await expect(settings.locator("#tts-voice")).toHaveValue("old-id");
    await input.fill("synthetic-key");
    await settings.getByRole("button", { name: "保存 Key", exact: true }).click();
    await expect(input).toHaveValue("");
    await expectVoiceChoices(3);
    await expect(settings.locator("#tts-voice")).toHaveValue("old-id");
    await expect(settings.locator("#tts-saved-voices")).toHaveAttribute("data-value", "manual");
    await settings.getByRole("button", { name: "加载更多" }).click();
    await expectVoiceChoices(4);
    await chooseSmart("tts-saved-voices", "saved:v2");
    await expect(settings.locator("#tts-voice")).toHaveCount(0);
    await expect(settings.locator("#tts-saved-voices")).toHaveAttribute("data-value", "saved:v2");
    await page.screenshot({ path: `${evidence}/${width}-saved-voice.png`, animations: "disabled" });
    await settings.getByRole("button", { name: "保存", exact: true }).click();
    await expect(settings.getByRole("status")).toContainText("设置已保存并启用");
    expect(state.voices.elevenlabs).toBe("v2");
    await expect(settings.locator("#tts-voice")).toHaveCount(0);
    await chooseSmart("tts-saved-voices", "manual");
    await expect(settings.getByText("语音输出设置已保存并启用。")).toHaveCount(0);
    await expect(settings.locator("#tts-voice")).toHaveValue("v2");
    await settings.locator("#tts-voice").fill("manual-id");
    await expect(settings.getByLabel("音色 ID")).toHaveCount(1);
    await input.fill("discard-on-leave");
    await page.goBack();
    await page.goBack();
    await page.goForward();
    await page.goForward();
    await expect(settings.locator("#tts-voice")).toHaveValue("manual-id");
    await expect(input).toHaveValue("");
    await settings.getByRole("button", { name: "保存", exact: true }).click();
    await expect(settings.getByRole("status")).toContainText("设置已保存并启用");
    expect(state.provider).toBe("elevenlabs");
    expect(state.voices.elevenlabs).toBe("manual-id");
    expect(voicePages.slice(0, 2)).toEqual([null, "next"]);
    await page.screenshot({ path: `${evidence}/${width}-settings.png`, animations: "disabled" });
    voiceAccessDenied = true;
    await chooseSmart("tts-provider", "minimax");
    await expect(settings.getByText("语音输出设置已保存并启用。")).toHaveCount(0);
    await chooseSmart("tts-provider", "elevenlabs");
    await expect(settings.getByRole("alert")).toContainText("无法读取已保存的音色");
    await expect(settings.locator("#tts-voice")).toHaveValue("manual-id");
    await settings.locator("#tts-voice").fill("another-id");
    await settings.getByRole("button", { name: "保存", exact: true }).click();
    await expect(settings.getByRole("status")).toContainText("设置已保存并启用");
    expect(state.voices.elevenlabs).toBe("another-id");
    voiceAccessDenied = false;
    voicesEmpty = true;
    await chooseSmart("tts-provider", "minimax");
    await chooseSmart("tts-provider", "elevenlabs");
    await expect(settings.getByText("没有找到已保存的音色，可以选择手动输入音色 ID。")).toBeVisible();
    await expect(settings.locator("#tts-voice")).toHaveValue("another-id");
    voicesEmpty = false;
    await settings.locator("#tts-voice").fill("uncertain-id");
    ambiguousSelection = true;
    await settings.getByRole("button", { name: "保存", exact: true }).click();
    await expect(settings.getByRole("alert")).toContainText("尚未确认设置");
    const attemptedSelections = selectionPosts;
    ambiguousSelection = false;
    await settings.getByRole("button", { name: "刷新" }).click();
    await expect(settings.locator("#tts-voice")).toHaveValue("another-id");
    expect(selectionPosts).toBe(attemptedSelections);
    await input.fill("not-saved");
    await page.goBack();
    await page.goForward();
    await expect(input).toHaveValue("");
    ambiguous = true;
    await input.fill("synthetic-replacement");
    await settings.getByRole("button", { name: "保存 Key", exact: true }).click();
    await expect(settings.getByRole("alert")).toContainText("尚未确认设置");
    expect(keyPosts).toBe(2);
    ambiguous = false;
    await settings.getByRole("button", { name: "刷新" }).click();
    await expect(input).toHaveValue("");
    expect(keyPosts).toBe(2);
    await page.goBack();
    await page.goBack();
    await expect(draft).toHaveValue("保留草稿");
    expect(errors).toEqual([]);
    await context.close();
  }
  for (const status of [404, 405, 501]) {
    const context = await browser.newContext({ locale: "zh-CN" });
    await context.addInitScript(denyNativeNotifications);
    const page = await context.newPage();
    await page.route("**/api/tts/settings", (route) => route.fulfill({ status }));
    await page.goto(`http://127.0.0.1:${server.port}/`);
    const capabilityProbe = page.waitForResponse((response) => new URL(response.url()).pathname === "/api/tts/settings" && response.status() === status);
    await page.getByRole("button", { name: "设置", exact: true }).click();
    await capabilityProbe;
    const settings = page.locator(".settings-screen");
    await expect(settings.getByRole("button", { name: "语音输入", exact: true })).toHaveCount(0);
    await expect(settings.getByRole("button", { name: "语音输出", exact: true })).toHaveCount(0);
    await context.close();
  }
  console.log("voice output settings: provider selection, saved voices, manual ID and recovery passed");
} finally {
  await browser.close();
  await server.close();
}
